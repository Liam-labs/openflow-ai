import { PRODUCT_NAME } from '@/lib/brand';
/**
 * Writing ~/.secrets safely. The file is a shell script that the owner's shells source, so anything written into it runs.
 * A value is therefore always single-quoted (nothing inside single quotes is interpreted by the shell; a quote inside the value
 * is written as '\'' ), names must look like ordinary variable names and must not be ones that change how a shell or program
 * behaves, and a value that cannot sit on one line is refused instead of being escaped.
 */

const NAME = /^[A-Z_][A-Z0-9_]*$/;
const DANGEROUS_NAME = /^(PATH|HOME|SHELL|IFS|ENV|BASH_ENV|BASH_FUNC_.*|PS[1-4]|PROMPT_COMMAND|SHELLOPTS|BASHOPTS|CDPATH|GLOBIGNORE|LD_.*|DYLD_.*|NODE_OPTIONS|NODE_PATH|PYTHON.*|PERL5?LIB|PERL5OPT|RUBYOPT|RUBYLIB|GIT_.*|SSH_ASKPASS|EDITOR|VISUAL|PAGER|BROWSER|LANG|LC_.*|OP_SERVICE_ACCOUNT_TOKEN)$/;

export function secretNameAllowed(name: string): boolean {
  return NAME.test(name) && !DANGEROUS_NAME.test(name);
}

export function secretValueAllowed(value: string): boolean {
  return typeof value === 'string' && value.length > 0 && value.length <= 8192 && !/[\0\r\n]/.test(value);
}

export function shellQuote(value: string): string {
  return "'" + value.replace(/'/g, "'\\''") + "'";
}

/** Existing `export NAME=...` lines in either form: the old double-quoted one (only `"` was escaped) and the single-quoted one. */
export function parseSecretsFile(text: string): Map<string, string> {
  const entries = new Map<string, string>();
  for (const line of text.split('\n')) {
    const double = line.match(/^export\s+([A-Z_][A-Z0-9_]*)="(.*)"\s*$/);
    if (double) { entries.set(double[1], double[2].replace(/\\"/g, '"')); continue; }
    const single = line.match(/^export\s+([A-Z_][A-Z0-9_]*)='((?:[^']|'\\'')*)'\s*$/);
    if (single) entries.set(single[1], single[2].replace(/'\\''/g, "'"));
  }
  return entries;
}

export interface SecretsUpdate {
  content: string;
  added: string[];
  updated: string[];
  refused: string[];
}

/** Add new keys and update changed ones in place. Refused names or values are listed (names only), never written. */
export function applySecrets(existing: string, wanted: Record<string, string>, now = new Date()): SecretsUpdate {
  const current = parseSecretsFile(existing);
  const refused: string[] = [];
  const toAdd: string[] = [];
  const toUpdate = new Map<string, string>();
  for (const [name, value] of Object.entries(wanted)) {
    if (!secretNameAllowed(name) || !secretValueAllowed(value)) { refused.push(name); continue; }
    if (!current.has(name)) toAdd.push(name);
    else if (current.get(name) !== value) toUpdate.set(name, value);
  }
  let text = existing;
  for (const [name, value] of toUpdate) {
    const lines = text.split('\n');
    const index = lines.findIndex((l) => new RegExp('^export\\s+' + name + '=').test(l));
    if (index >= 0) lines[index] = `export ${name}=${shellQuote(value)}`;
    text = lines.join('\n');
  }
  const addLines = toAdd.map((name) => `export ${name}=${shellQuote(wanted[name])}`);
  let content = text;
  if (!existing && addLines.length) {
    content = [`# ~/.secrets - Generated by ${PRODUCT_NAME} Setup Wizard`, `# Created: ${now.toISOString()}`, '', ...addLines, ''].join('\n');
  } else if (addLines.length) {
    content = text.trimEnd() + `\n\n# ===== ${PRODUCT_NAME} Setup Wizard =====\n` + addLines.join('\n') + '\n';
  }
  return { content, added: toAdd, updated: [...toUpdate.keys()], refused };
}
