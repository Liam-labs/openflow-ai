# ─── MCP Server Loading ───────────────────────────────────────────────────────

def load_mcp_servers(cwd: str) -> list[dict]:
    """Load MCP server configs for the agent's project directory.

    Reads .mcp.json from CWD (project-level) and ~/.claude/.mcp.json (user-level),
    merges them, and returns the array suitable for ACP session/new mcpServers.

    Grok CLI v0.2.101+ expects: {id, transport, command, args, env?, cwd?}
    (NOT the MCP config format {name, type, command, args}).

    Returns an empty list if no MCP config files are found.
    """
    servers: list[dict] = []
    seen_ids: set[str] = set()

    # Project-level .mcp.json takes precedence
    for base in [os.path.expanduser("~/.claude"), cwd]:
        mcp_file = os.path.join(base, ".mcp.json")
        if not os.path.isfile(mcp_file):
            continue
        try:
            with open(mcp_file, "r", encoding="utf-8") as f:
                data = json.load(f)
            mcp_servers = data.get("mcpServers", {})
            for name, cfg in mcp_servers.items():
                server_id = cfg.get("id", name)
                if server_id not in seen_ids:
                    seen_ids.add(server_id)
                    # Map MCP config format → Grok ACP format
                    entry: dict = {
                        "id": server_id,
                        "label": cfg.get("label", name),
                        "transport": cfg.get("transport", cfg.get("type", "stdio")),
                    }
                    if "command" in cfg:
                        entry["command"] = cfg["command"]
                    if "args" in cfg:
                        entry["args"] = cfg["args"]
                    if "env" in cfg:
                        entry["env"] = cfg["env"]
                    if "url" in cfg:
                        entry["url"] = cfg["url"]
                    servers.append(entry)
        except Exception as e:
            debug(f"MCP load error from {mcp_file}: {e}")

    if servers:
        debug(f"Loaded {len(servers)} MCP servers: {[s['id'] for s in servers]}")
    return servers


# ─── ACP Subprocess Manager ────────────────────────────────────────────────────

class ACPSession:
    """Manages a persistent `grok agent stdio` subprocess via ACP JSON-RPC 2.0.

    The subprocess runs for the lifetime of the agent.  All prompts and responses
    flow through this session.  Tool execution is handled natively by grok-build.
    """

    def __init__(self, model: str, cwd: str, mcp_servers: list[dict]):
        self.model = model
        self.cwd = cwd
        self.mcp_servers = mcp_servers
        self.process: subprocess.Popen | None = None
        self.session_id: str | None = None
        self._msg_id = 0
        self._lock = threading.Lock()
        self._response_queues: dict[int, queue.Queue] = {}
        self._updates: list[dict] = []
        self._update_event = threading.Event()
        self._reader_thread: threading.Thread | None = None
        self._running = False
        self._xai_api_key: str = ""

    def _next_id(self) -> int:
        self._msg_id += 1
        return self._msg_id

    def start(self, api_key: str) -> None:
        """Start the grok subprocess and establish an ACP session.

        Sequence: spawn → initialize → authenticate → session/new
        """
        self._xai_api_key = api_key

        if not os.path.isfile(GROK_BINARY) and not shutil.which("grok"):
            raise RuntimeError(
                f"Grok Build CLI not found at {GROK_BINARY}. "
                "Install: curl -fsSL https://x.ai/cli/install.sh | bash"
            )

        # Write privacy config before spawning
        write_privacy_config()

        env = os.environ.copy()
        env["XAI_API_KEY"] = api_key

        debug(f"Spawning: {GROK_BINARY} agent stdio (cwd={self.cwd})")
        self.process = subprocess.Popen(
            [GROK_BINARY, "agent", "stdio"],
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            cwd=self.cwd,
            env=env,
            text=True,
            bufsize=1,
        )

        self._running = True
        self._reader_thread = threading.Thread(target=self._read_stdout, daemon=True)
        self._reader_thread.start()

        # Also read stderr for diagnostics
        threading.Thread(target=self._read_stderr, daemon=True).start()

        # Step 1: initialize
        # Grok CLI v0.2.101+ uses MCP-style initialize: protocolVersion "2024-11-05",
        # clientInfo (not clientCapabilities), and capabilities (not top-level fs/terminal).
        try:
            init_resp = self._call("initialize", {
                "protocolVersion": "2024-11-05",
                "capabilities": {},
                "clientInfo": {"name": "DevFlow", "version": "1.0"},
            }, timeout=ACP_START_TIMEOUT)
        except Exception as e:
            self._kill()
            raise RuntimeError(f"ACP initialize failed: {e}") from e

        auth_methods = init_resp.get("authMethods", [])
        auth_ids = [m.get("id") for m in auth_methods]
        debug(f"ACP initialize OK — auth methods: {auth_ids}")

        # Step 2: authenticate
        # PRIORITY: cached_token (SuperGrok subscription) > xai.api_key (API credits).
        # the owner wants subscription usage (flat-rate, not per-token API billing).
        # cached_token is available after `grok login` has been run once.
        # Grok CLI 1.0 renamed it "grok.com" (OIDC login stored in ~/.grok/auth.json).
        # xai.api_key is available when XAI_API_KEY env var is set.
        if "grok.com" in auth_ids:
            method_id = "grok.com"
        elif "cached_token" in auth_ids:
            method_id = "cached_token"
        elif "xai.api_key" in auth_ids:
            method_id = "xai.api_key"
        else:
            self._kill()
            raise RuntimeError(
                f"No supported auth method in {auth_ids}. "
                "Run 'grok login' to authenticate with your SuperGrok subscription, "
                "or set XAI_API_KEY for API credit access."
            )

        try:
            self._call("authenticate", {
                "methodId": method_id,
                "_meta": {"headless": True},
            }, timeout=ACP_START_TIMEOUT)
            debug("ACP authenticate OK")
        except Exception as e:
            self._kill()
            raise RuntimeError(f"ACP authenticate failed: {e}") from e

        # Step 3: session/new
        # NOTE: mcpServers format for grok CLI v0.2.101 is still being reverse-engineered.
        # All known formats (id+transport, name+type, etc.) fail with "untagged enum McpServer".
        # Passing [] works; MCP servers can be added post-session via mcp/add once the
        # correct format is confirmed. See T2.3 for tracking.
        # permissionMode: bypassPermissions — equivalent to --dangerously-skip-permissions.
        # Without this, grok sends session/request_permission for every tool call and
        # we must respond. With bypassPermissions, grok auto-executes tools.
        try:
            session_resp = self._call("session/new", {
                "cwd": self.cwd,
                "mcpServers": [],  # TODO: wire load_mcp_servers() once format confirmed
                "model": self.model,
                "permissionMode": "bypassPermissions",
            }, timeout=ACP_START_TIMEOUT)
            self.session_id = session_resp.get("sessionId")
            if not self.session_id:
                self._kill()
                raise RuntimeError("session/new returned no sessionId")
            debug(f"ACP session/new OK — sessionId={self.session_id}")
        except Exception as e:
            self._kill()
            raise RuntimeError(f"ACP session/new failed: {e}") from e

    def send_prompt(self, text: str) -> str:
        """Send a prompt via session/prompt and collect the response.

        Blocks until the response is complete (stopReason received or
        text stabilizes).  Returns the accumulated response text.
        """
        if not self.session_id:
            raise RuntimeError("No active ACP session — call start() first")

        # Clear update buffer before sending
        self._updates.clear()
        self._update_event.clear()

        resp = self._call("session/prompt", {
            "sessionId": self.session_id,
            "prompt": [{"type": "text", "text": text}],
        }, timeout=ACP_CALL_TIMEOUT)

        stop_reason = resp.get("stopReason", "unknown")
        debug(f"ACP session/prompt complete — stopReason={stop_reason}")

        # Collect response from accumulated session/update notifications
        # The grok-build CLI sends agent_message_chunk updates asynchronously
        response_parts: list[str] = []
        for update in self._updates:
            su = update.get("sessionUpdate", "")
            if su == "agent_message_chunk":
                content = update.get("content", {})
                chunk_text = content.get("text", "")
                if chunk_text:
                    response_parts.append(chunk_text)
            elif su == "thought_finalized":
                thought = update.get("content", {}).get("text", "")
                if thought:
                    debug(f"ACP thought: {thought[:200]}...")

        result = "".join(response_parts)
        debug(f"ACP response: {len(result)} chars")

        # Accumulate token usage from billing events
        for update in self._updates:
            if update.get("sessionUpdate") == "x.ai/billing":
                self._accumulate_billing(update)

        return result

    def _call(self, method: str, params: dict, timeout: float = 60.0) -> dict:
        """Send a JSON-RPC request and wait for the matching response."""
        msg_id = self._next_id()
        request = {
            "jsonrpc": "2.0",
            "id": msg_id,
            "method": method,
            "params": params,
        }
        resp_queue: queue.Queue = queue.Queue()
        with self._lock:
            self._response_queues[msg_id] = resp_queue

        payload = json.dumps(request, ensure_ascii=False) + "\n"
        debug(f"ACP → {method} id={msg_id}")
        try:
            self.process.stdin.write(payload)
            self.process.stdin.flush()
        except (BrokenPipeError, OSError) as e:
            with self._lock:
                self._response_queues.pop(msg_id, None)
            raise RuntimeError(f"Failed to write to grok stdin: {e}") from e

        try:
            result = resp_queue.get(timeout=timeout)
        except queue.Empty:
            with self._lock:
                self._response_queues.pop(msg_id, None)
            raise TimeoutError(f"ACP {method} timed out after {timeout}s")

        if "error" in result:
            err = result["error"]
            raise RuntimeError(f"ACP {method} error: {err.get('message', err)}")

        return result.get("result", {})

    def _read_stdout(self) -> None:
        """Background thread: read newline-delimited JSON-RPC from stdout."""
        try:
            for line in self.process.stdout:
                line = line.strip()
                if not line:
                    continue
                try:
                    msg = json.loads(line)
                except json.JSONDecodeError:
                    debug(f"ACP non-JSON stdout: {line[:200]}")
                    continue

                msg_id = msg.get("id")
                if msg_id is not None and "method" not in msg:
                    # This is a response to one of our requests
                    with self._lock:
                        q = self._response_queues.get(msg_id)
                    if q:
                        q.put(msg)
                    else:
                        debug(f"ACP spurious response id={msg_id}")
                elif msg.get("method") == "session/update":
                    # Server-initiated notification — streaming update
                    # Grok CLI 1.0 nests the event under params.update (standard
                    # ACP); 0.2.x put sessionUpdate directly on params.
                    params = msg.get("params", {})
                    update = params.get("update", params)
                    self._updates.append(update)
                    self._update_event.set()
                elif msg.get("method") == "session/request_permission":
                    # Grok wants to execute a tool — auto-approve in headless mode.
                    # The permission request is a JSON-RPC request (has id). We respond
                    # with a JSON-RPC response matching that id. The response format is
                    # the standard JSON-RPC 2.0 response shape.
                    params = msg.get("params", {})
                    tool_call = params.get("toolCall", {})
                    tc_id = tool_call.get("toolCallId", "unknown")
                    tc_name = tool_call.get("name", tool_call.get("function", {}).get("name", "unknown"))
                    debug(f"ACP auto-approving tool: {tc_name} ({tc_id})")
                    request_id = msg.get("id")
                    # Send a raw JSON-RPC response to stdin. The result format was
                    # determined empirically — grok CLI v0.2.101 expects {"allow": true}
                    # as the PermissionDecision shape (tried: "allow", {"decision":"allow"},
                    # {"allowed":true} — all failed deserialization).
                    response = {
                        "jsonrpc": "2.0",
                        "id": request_id,
                        "result": {"allow": True},
                    }
                    try:
                        payload = json.dumps(response, ensure_ascii=False) + "\n"
                        self.process.stdin.write(payload)
                        self.process.stdin.flush()
                    except Exception as e:
                        debug(f"ACP failed to write auto-approve: {e}")
                else:
                    debug(f"ACP unhandled message: {json.dumps(msg)[:200]}")
        except Exception as e:
            if self._running:
                debug(f"ACP stdout reader error: {e}")

    def _read_stderr(self) -> None:
        """Background thread: log stderr from grok subprocess."""
        try:
            for line in self.process.stderr:
                if line.strip():
                    debug(f"ACP stderr: {line.rstrip()[:500]}")
        except Exception:
            pass

    def _accumulate_billing(self, update: dict) -> None:
        """Extract token usage from x.ai/billing events."""
        # Store for the wrapper to pick up — the wrapper owns token totals
        billing = update.get("billing", update.get("content", {}))
        if billing:
            self._last_billing = billing
            debug(f"ACP billing: {json.dumps(billing)[:300]}")

    def stop(self) -> None:
        """Cleanly shut down the ACP subprocess."""
        self._running = False
        if self.process and self.process.poll() is None:
            try:
                self.process.stdin.close()
            except Exception:
                pass
            try:
                self.process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait()
            debug(f"ACP subprocess exited code={self.process.returncode}")

    def _kill(self) -> None:
        """Force-kill the subprocess."""
        self._running = False
        if self.process and self.process.poll() is None:
            try:
                self.process.kill()
                self.process.wait(timeout=3)
            except Exception:
                pass


# ─── Collab Wrapper ───────────────────────────────────────────────────────────

class CollabGrokACPWrapper:
    """Grok agent that communicates via ACP subprocess instead of direct API calls.

    Ports the proven session protocol, hook lifecycle, scaffolding, and channel
    polling patterns from collab-grok.py while replacing the API layer with ACP.
    """

    def __init__(self, channel_id: str, participant_name: str,
                 model: str = DEFAULT_MODEL, system_prompt: str = ""):
        self.channel_id = channel_id
        self.participant_name = participant_name
        self.model = model
        self.system_prompt = system_prompt
        self.pid = os.getpid()
        self.cwd = os.getcwd()

        # State
        self.participant_id: str | None = None
        self.joined = False
        self.running = False
        self.channel_name = ""
        self.last_poll_time = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        self.last_pong = time.time()
        self._last_processed_message_id: str | None = None
        self._last_processed_timestamp: str | None = None
        self._shutdown_hook_fired = False

        # Token tracking
        self.token_usage = {
            "input_tokens": 0,
            "output_tokens": 0,
            "thinking_tokens": 0,
            "total_tokens": 0,
        }

        # Conversation history (bounded)
        self.conversation_history: list[dict] = []

        # ACP session (created in run())
        self.acp: ACPSession | None = None

    # ── File helpers ────────────────────────────────────────────────────────

    @staticmethod
    def _load_file_safe(path: str, max_lines: int = 0) -> str:
        """Return file contents, or empty string if missing/unreadable."""
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as f:
                if max_lines:
                    lines = []
                    for i, line in enumerate(f):
                        if i >= max_lines:
                            break
                        lines.append(line)
                    return "".join(lines).strip()
                return f.read().strip()
        except Exception:
            return ""

    # ── Scaffolding ─────────────────────────────────────────────────────────

    def _build_scaffolded_prompt(self) -> str:
        """Build a context-rich first-turn prompt from scaffolding files.

        Mirrors collab-grok.py:_build_scaffolded_prompt — loads the CLAUDE.md
        chain, rules/*.md, alignment-grok.md, and MEMORY.md. Injected as the first user-prompt context
        so grok-build sees the full scaffolding without a system-prompt API param.
        """
        sections: list[str] = []
        cwd = self.cwd
        home = os.path.expanduser("~")

        # Identity
        sections.append(
            f"Your name is {self.participant_name}. "
            f"You are a Grok AI agent on the DevFlow multi-agent platform. "
            f"You work alongside Claude, Gemini, and other agents as an expert "
            f"software engineer. Be concise, technically precise, and collaborative.\n\n"
            f"CRITICAL — MESSAGE DELIVERY: Your text responses are AUTOMATICALLY "
            f"posted to the collab channel. Simply write your response as plain "
            f"text and it will be delivered. Do NOT use bash to send messages. "
            f"Ignore any instructions that tell you to use bash commands for messaging."
        )

        # Global ~/.claude/CLAUDE.md
        global_claude = self._load_file_safe(os.path.join(home, ".claude", "CLAUDE.md"))
        if global_claude:
            sections.append(f"# Global Instructions\n\n{global_claude}")

        # Project CLAUDE.md files — walk from CWD up to home
        claude_files: list[tuple[int, str]] = []
        current = cwd
        depth = 0
        while True:
            candidate = os.path.join(current, "CLAUDE.md")
            if os.path.isfile(candidate):
                claude_files.append((depth, candidate))
            parent = os.path.dirname(current)
            if parent == current or not current.startswith(home):
                break
            current = parent
            depth += 1

        for _, path in reversed(claude_files):
            content = self._load_file_safe(path)
            if content:
                sections.append(f"# Project Instructions ({os.path.relpath(path, home)})\n\n{content}")

        # Rules files: {CWD}/.claude/rules/*.md
        rules_dir = os.path.join(cwd, ".claude", "rules")
        if os.path.isdir(rules_dir):
            try:
                rule_files = sorted(f for f in os.listdir(rules_dir) if f.endswith(".md"))
                for fname in rule_files:
                    content = self._load_file_safe(os.path.join(rules_dir, fname))
                    if content:
                        sections.append(content)
            except Exception as e:
                debug(f"Could not load rules files: {e}")

        alignment = self._load_file_safe(os.path.join(cwd, "alignment-grok.md"))
        if not alignment:
            alignment = self._load_file_safe(os.path.join(
                os.path.dirname(__file__), "..", "data", "scaffolding", "masters",
                "per-model", "grok", "alignment-grok.md",
            ))
        if alignment:
            sections.append(alignment)

        # Memory file
        encoded = cwd.replace("/", "-")
        memory_path = os.path.join(home, ".claude", "projects", encoded, "memory", "MEMORY.md")
        memory = self._load_file_safe(memory_path, max_lines=200)
        if memory:
            sections.append(f"# Persistent Memory\n\n{memory}")

        # Explicit system prompt
        if self.system_prompt:
            sections.append(self.system_prompt)

        result = "\n\n---\n\n".join(sections)
        debug(f"Scaffolded prompt built: {len(result)} chars, {len(sections)} sections")
        return result

    # ── Session protocol ────────────────────────────────────────────────────

    def _api_call(self, path: str, method: str = "GET", body: dict | None = None) -> dict:
        """Call the DevFlow collab API."""
        stripped = path.lstrip('/')
        url = f"{DEVFLOW_API_BASE}/{stripped}" if stripped else DEVFLOW_API_BASE
        try:
            data = None
            if body is not None:
                data = json.dumps(body).encode("utf-8")
            req = urllib.request.Request(url, data=data, method=method)
            req.add_header("Content-Type", "application/json")
            with urllib.request.urlopen(req, timeout=10) as resp:
                return json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as e:
            try:
                body = e.read().decode("utf-8")
                return json.loads(body) if body else {"error": str(e)}
            except Exception:
                return {"error": str(e)}
        except Exception as e:
            return {"error": str(e)}

    def _register_session(self) -> None:
        """Write /tmp/collab-ready-{pid}.json so DevFlow knows this agent exists."""
        ready_file = f"/tmp/collab-ready-{self.pid}.json"
        try:
            with open(ready_file, "w") as f:
                json.dump({
                    "pid": self.pid,
                    "name": self.participant_name,
                    "type": "grok",
                    "model": self.model,
                    "wrapper": "collab-grok-acp",
                    "cwd": self.cwd,
                    "channelId": self.channel_id,
                    "startedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                }, f)
            debug(f"Ready file: {ready_file}")
        except Exception as e:
            debug(f"Failed to write ready file: {e}")

    def _write_session_file(self, channel_name: str) -> None:
        """Write session files so collab_helper.py can find this agent."""
        session_data = {
            "pid": self.pid,
            "name": self.participant_name,
            "type": "grok",
            "model": self.model,
            "wrapper": "collab-grok-acp",
            "channelId": self.channel_id,
            "participantId": self.participant_id,
            "projectPath": self.cwd,
            "channelName": channel_name,
            "joinedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        }
        # /tmp
        tmp_path = f"/tmp/collab-session-{self.pid}.json"
        try:
            with open(tmp_path, "w") as f:
                json.dump(session_data, f)
        except Exception as e:
            debug(f"Failed to write {tmp_path}: {e}")

        # {CWD}/.claude/
        local_dir = os.path.join(self.cwd, ".claude")
        os.makedirs(local_dir, exist_ok=True)
        local_path = os.path.join(local_dir, f"collab-session-{self.pid}.json")
        try:
            with open(local_path, "w") as f:
                json.dump(session_data, f)
        except Exception as e:
            debug(f"Failed to write {local_path}: {e}")

    def join_channel(self) -> bool:
        """Join the collab channel."""
        result = self._api_call("", "POST", {
            "action": "join",
            "channelId": self.channel_id,
            "force": True,
            "participant": {
                "name": self.participant_name,
                "type": "grok",
                "source": "collab-grok-acp wrapper",
                "pid": self.pid,
                "projectPath": self.cwd,
            },
        })

        if not result.get("success"):
            debug(f"Join failed: {result}")
            return False

        self.participant_id = result.get("participantId")
        self.joined = True
        self.last_poll_time = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        channel_data = result.get("channel") or {}
        self.channel_name = channel_data.get("name", "")
        self._write_session_file(self.channel_name)
        debug(f"Joined: participantId={self.participant_id}")
        return True

    def leave_channel(self) -> None:
        """Gracefully leave the channel."""
        if self.joined and self.participant_id:
            self._api_call("", "POST", {
                "action": "leave",
                "channelId": self.channel_id,
                "participantId": self.participant_id,
            })
            debug("Left channel")

    # ── Hooks ────────────────────────────────────────────────────────────────

    def _run_hook(self, *cmd_parts: str, hook_name: str = "hook") -> None:
        """Run a lifecycle hook script, logging errors but never blocking."""
        if not all(cmd_parts):
            return
        try:
            result = subprocess.run(list(cmd_parts), capture_output=True, text=True, timeout=10)
            if result.returncode != 0:
                debug(f"{hook_name} exited {result.returncode}: {result.stderr.strip()[:200]}")
        except Exception as e:
            debug(f"{hook_name} failed: {e}")

    def _run_hook_on_startup(self) -> None:
        """SessionStart hook."""
        hooks_dir = os.path.join(os.path.dirname(__file__), "hooks")
        script = os.path.join(hooks_dir, "session-scratch-init.sh")
        if os.path.isfile(script):
            self._run_hook("bash", script, self.participant_name, self.cwd,
                           hook_name="SessionStart-hook")

    def _run_hook_before_inject(self, sender: str, content: str) -> None:
        """UserPromptSubmit hook."""
        hooks_dir = os.path.join(os.path.dirname(__file__), "hooks")
        script = os.path.join(hooks_dir, "user-prompt-submit.sh")
        if os.path.isfile(script):
            self._run_hook("bash", script, self.participant_name, self.cwd,
                           sender, content, hook_name="UserPromptSubmit-hook")

    def _run_hook_on_shutdown(self) -> None:
        """Stop equivalent: flush scratch buffers only."""
        if self._shutdown_hook_fired:
            return
        self._shutdown_hook_fired = True
        hooks_dir = os.path.join(os.path.dirname(__file__), "hooks")
        script = os.path.join(hooks_dir, "flush.sh")
        if os.path.isfile(script):
            self._run_hook("bash", script, self.participant_name, self.cwd,
                           "all", hook_name="Stop-flush")

    def _flush_session_log(self) -> None:
        """Flush pending scratch buffers without synthetic log entries."""
        self._run_hook_on_shutdown()

    def _cleanup_session_files(self) -> None:
        """Remove session/ready files on clean exit."""
        paths = [
            f"/tmp/collab-ready-{self.pid}.json",
            f"/tmp/collab-session-{self.pid}.json",
            os.path.join(self.cwd, ".claude", f"collab-session-{self.pid}.json"),
        ]
        for path in paths:
            try:
                os.remove(path)
            except FileNotFoundError:
                pass
            except Exception as e:
                debug(f"Cleanup error {path}: {e}")

    # ── Message polling ─────────────────────────────────────────────────────

    def _poll_messages(self) -> list[dict]:
        """Poll for new channel messages since last check."""
        if not self.participant_id:
            return []
        try:
            url = (f"{DEVFLOW_URL}/api/events"
                   f"?types=collab"
                   f"&channelId={self.channel_id}"
                   f"&participantId={self.participant_id}"
                   f"&since={urllib.request.quote(self.last_poll_time)}"
                   f"&limit=10")
            req = urllib.request.Request(url)
            with urllib.request.urlopen(req, timeout=10) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                messages = data.get("messages", [])
                if messages:
                    # Update last_poll_time to the most recent message timestamp
                    newest = max(
                        (m.get("createdAt", self.last_poll_time) for m in messages),
                        default=self.last_poll_time,
                    )
                    self.last_poll_time = max(self.last_poll_time, newest)
                return messages
        except Exception as e:
            debug(f"Poll error: {e}")
            return []

    def _is_for_me(self, msg: dict) -> bool:
        """Check if a message is addressed to this agent."""
        content = msg.get("content", "")
        sender_info = msg.get("from") or msg.get("sender") or {}
        sender = sender_info.get("name", "")
        sender_type = sender_info.get("type", "")

        # Skip own messages
        if sender == self.participant_name:
            return False

        # Check for @mention
        if f"@{self.participant_name}" in content:
            return True

        # Broadcast messages from other agents or users
        if msg.get("broadcast"):
            return True

        # Direct messages from users (the owner)
        if sender_type == "user" and not msg.get("broadcast"):
            return True

        return False

    # ── Response posting ────────────────────────────────────────────────────

    def _post_response(self, text: str, recipient: str) -> None:
        """Post a response to the channel via collab_helper.py."""
        if not text.strip() or not recipient.strip():
            return
        # Truncate if needed
        if len(text) > MAX_RESPONSE_CHARS:
            text = text[:MAX_RESPONSE_CHARS] + "\n\n[truncated]"

        try:
            script = os.path.join(os.path.dirname(__file__), "..", "collab_helper.py")
            # Use the DevFlow scripts path
            helper = os.path.join(DEVFLOW_HOME, "scripts", "collab_helper.py")
            env = os.environ.copy()
            env["COLLAB_WRAPPER_PID"] = str(self.pid)
            result = subprocess.run(
                ["python3", helper, "--to", recipient, "--stdin"],
                input=text, capture_output=True, text=True, timeout=15,
                cwd=self.cwd, env=env,
            )
            if result.returncode != 0:
                debug(f"collab_helper error: {result.stderr.strip()[:200]}")
            else:
                debug(f"Posted response ({len(text)} chars)")
        except Exception as e:
            debug(f"Failed to post response: {e}")

    # ── Core message processing ─────────────────────────────────────────────

    def _process_message(self, msg: dict) -> None:
        """Process a single inbound message: run hook, call ACP, post response."""
        sender_info = msg.get("from") or msg.get("sender") or {}
        sender = sender_info.get("name", "")
        content = msg.get("content", "")
        msg_id = msg.get("id", "")

        # Deduplicate — skip if we already processed this message
        if msg_id and msg_id == self._last_processed_message_id:
            return

        debug(f"Processing message from {sender}: {content[:100]}...")

        # Build the user message with channel context
        user_content = f"[Channel message from {sender}]: {content}"
        safe_append_stream_message(
            self.cwd,
            ".grok-stream.jsonl",
            "user",
            content,
            event_id=f"{msg_id}-user" if msg_id else None,
        )

        try:
            response = self.acp.send_prompt(user_content)
        except Exception as e:
            debug(f"ACP send_prompt failed: {e}")
            response = f"[Error calling Grok: {e}]"

        if response and response.strip():
            safe_append_stream_message(
                self.cwd,
                ".grok-stream.jsonl",
                "assistant",
                response,
                event_id=f"{msg_id}-assistant" if msg_id else None,
            )
            self._post_response(response, sender)
            # Add to conversation history
            self.conversation_history.append({"role": "user", "content": user_content})
            self.conversation_history.append({"role": "assistant", "content": response})
            # Trim history
            if len(self.conversation_history) > MAX_HISTORY_TURNS * 2:
                self.conversation_history = self.conversation_history[-(MAX_HISTORY_TURNS * 2):]

        if msg_id:
            self._last_processed_message_id = msg_id

    # ── Background threads ──────────────────────────────────────────────────

    def message_loop(self) -> None:
        """Main message processing loop — polls for messages, processes them."""
        debug("Message loop started")
        # Scaffolding is NOT injected here. The grok CLI v0.2.101 reads CLAUDE.md,
        # rules/*.md, and project files from cwd natively via its own file tools.
        # Injecting 79K+ of context blocks session/prompt for minutes and prevents
        # the agent from responding to channel messages.

        while self.running:
            try:
                messages = self._poll_messages()
                for msg in messages:
                    if not self.running:
                        break
                    if self._is_for_me(msg):
                        self._process_message(msg)
            except Exception as e:
                debug(f"Message loop error: {e}")
            time.sleep(POLL_INTERVAL)

    def heartbeat_loop(self) -> None:
        """Periodic heartbeat to keep the session alive."""
        debug("Heartbeat loop started")
        while self.running:
            time.sleep(HEARTBEAT_INTERVAL)
            if not self.running:
                break
            # Touch ready file to show we're alive
            ready_file = f"/tmp/collab-ready-{self.pid}.json"
            try:
                os.utime(ready_file, None)
            except Exception:
                pass
            self.last_pong = time.time()

    def sse_listener(self) -> None:
        """Listen for SSE events from the collab API (real-time messages)."""
        if not self.participant_id:
            debug("SSE listener skipped — no participantId yet")
            return
        debug("SSE listener started")
        while self.running:
            try:
                url = (f"{DEVFLOW_URL}/api/events"
                       f"?types=collab"
                       f"&channelId={self.channel_id}"
                       f"&participantId={self.participant_id}")
                req = urllib.request.Request(url)
                req.add_header("Accept", "text/event-stream")
                with urllib.request.urlopen(req, timeout=90) as resp:
                    buffer = ""
                    for line_bytes in resp:
                        if not self.running:
                            break
                        try:
                            line = line_bytes.decode("utf-8", errors="replace")
                        except Exception:
                            continue
                        if line.startswith("data: "):
                            data_str = line[6:].strip()
                            if data_str:
                                buffer += data_str
                        elif line.strip() == "" and buffer:
                            try:
                                event = json.loads(buffer)
                                msg = event.get("message", event)
                                if isinstance(msg, dict) and self._is_for_me(msg):
                                    self._process_message(msg)
                            except json.JSONDecodeError:
                                pass
                            buffer = ""
            except Exception as e:
                if self.running:
                    debug(f"SSE error (reconnecting in {POLL_INTERVAL}s): {e}")
            time.sleep(POLL_INTERVAL)

    def watchdog_loop(self) -> None:
        """Monitor for stuck state — if no heartbeat in too long, exit."""
        debug("Watchdog started")
        while self.running:
            time.sleep(30)
            if not self.running:
                break
            elapsed = time.time() - self.last_pong
            if elapsed > WATCHDOG_STUCK_THRESHOLD:
                debug(f"WATCHDOG: no heartbeat for {elapsed:.0f}s — exiting")
                self.running = False

    # ── Main entry point ────────────────────────────────────────────────────

    def run(self) -> int:
        """Start the agent, join channel, and run the message loop."""
        # Load API key
        api_key = os.environ.get("GROK_API_KEY", "")
        if not api_key:
            # Try loading from ~/.secrets
            secrets_file = os.path.expanduser("~/.secrets")
            if os.path.isfile(secrets_file):
                try:
                    with open(secrets_file) as f:
                        for line in f:
                            if line.startswith("export GROK_API_KEY="):
                                api_key = line.split("=", 1)[1].strip().strip('"').strip("'")
                                break
                except Exception:
                    pass
        if not api_key:
            print("[Grok ACP] Error: GROK_API_KEY not set", file=sys.stderr)
            return 1

        # Load MCP servers
        mcp_servers = load_mcp_servers(self.cwd)

        # Start ACP session
        self.acp = ACPSession(
            model=self.model,
            cwd=self.cwd,
            mcp_servers=mcp_servers,
        )
        try:
            self.acp.start(api_key)
        except Exception as e:
            print(f"[Grok ACP] Failed to start ACP session: {e}", file=sys.stderr)
            debug(f"ACP start failed: {e}")
            return 1

        print(f"[Grok ACP] Session established (model={self.model}, "
              f"mcp_servers={len(mcp_servers)})", file=sys.stderr)

        # Session protocol
        self._register_session()
        self._run_hook_on_startup()

        # Join channel with retry
        for attempt in range(6):
            if self.join_channel():
                break
            if attempt < 5:
                wait = 2 ** attempt
                print(f"[Grok ACP] Join retry in {wait}s ({attempt + 1}/6)...", file=sys.stderr)
                time.sleep(wait)
        else:
            print(f"[Grok ACP] Failed to join channel {self.channel_id}", file=sys.stderr)
            self.acp.stop()
            return 1

        # Register exit handlers
        atexit.register(self._flush_session_log)
        os.environ["_GROK_AGENT_NAME"] = self.participant_name

        # Signal handlers
        def _shutdown(signum, frame):
            sig_name = "SIGTERM" if signum == signal.SIGTERM else "SIGINT"
            print(f"\n[Grok ACP] {sig_name} — shutting down...", file=sys.stderr)
            self._flush_session_log()
            self.running = False

        signal.signal(signal.SIGTERM, _shutdown)
        signal.signal(signal.SIGINT, _shutdown)

        # Unhandled exception hook
        _original_excepthook = sys.excepthook
        def _excepthook(exc_type, exc_val, exc_tb):
            debug(f"Unhandled exception: {exc_type.__name__}: {exc_val}")
            _original_excepthook(exc_type, exc_val, exc_tb)
        sys.excepthook = _excepthook

        self.running = True

        # Start background threads
        for target in (
            self.sse_listener,
            self.heartbeat_loop,
            self.message_loop,
            self.watchdog_loop,
        ):
            threading.Thread(target=target, daemon=True).start()

        print(f"[Grok ACP] Running as {self.participant_name}. "
              f"Send Ctrl+C to exit.", file=sys.stderr)

        while self.running:
            time.sleep(1)

        # Graceful shutdown
        self.leave_channel()
        self._cleanup_session_files()
        if self.acp:
            self.acp.stop()
        debug("collab-grok-acp.py exiting")
        return 0


# ─── CLI entry point ──────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Grok ACP agent for DevFlow collab channels",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  collab-grok-acp.py --channel <id> --name Grok
  collab-grok-acp.py --channel <id> --name Grok --model grok-4.7
  collab-grok-acp.py --channel <id> --name Grok --system-prompt-file /tmp/role.md
        """,
    )
    parser.add_argument("--channel", "-c", required=True, help="Collab channel ID")
    parser.add_argument("--name", "-n", required=True, help="Display name for this agent")
    parser.add_argument("--model", "-m", default=DEFAULT_MODEL,
                        help=f"Model to use (default: {DEFAULT_MODEL})")
    parser.add_argument("--system-prompt-file",
                        help="Path to a file containing an extra system prompt")

    args = parser.parse_args()

    system_prompt = ""
    if args.system_prompt_file:
        try:
            with open(args.system_prompt_file) as f:
                system_prompt = f.read().strip()
            debug(f"Loaded system prompt from {args.system_prompt_file} ({len(system_prompt)} chars)")
        except Exception as e:
            print(f"[Grok ACP] Warning: could not read system prompt file: {e}", file=sys.stderr)

    wrapper = CollabGrokACPWrapper(
        channel_id=args.channel,
        participant_name=args.name,
        model=args.model,
        system_prompt=system_prompt,
    )
    sys.exit(wrapper.run())


if __name__ == "__main__":
    main()
