#!/usr/bin/env python3
"""Download the web fonts the dashboard uses into public/fonts/ and write app/fonts-local.css, so the app never asks Google for them.

  python3 scripts/fetch-fonts.py

Run it only when the font list changes; the files and the CSS are committed. Keeps the latin and latin-ext subsets of the text
fonts. All are SIL Open Font License 1.1, free to redistribute. (The Material Symbols icon font is not used anywhere, so it is not fetched.)
"""
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"   # asks Google for woff2
TEXT = "https://fonts.googleapis.com/css2?family=Syne:wght@600;700;800&family=JetBrains+Mono:wght@400;500;700&family=IBM+Plex+Sans:wght@400;500;600&display=swap"
KEEP = {"latin", "latin-ext"}


def get(url: str) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=60) as r:
        return r.read()


def main() -> int:
    out_dir = ROOT / "public" / "fonts"
    out_dir.mkdir(parents=True, exist_ok=True)
    css_parts = ["/* Generated by scripts/fetch-fonts.py. Local copies of the dashboard fonts (SIL OFL 1.1). */"]
    saved: dict[str, str] = {}
    text_css = get(TEXT).decode()
    for subset, block in re.findall(r"/\* ([a-z-]+) \*/\s*(@font-face \{.*?\})", text_css, re.S):
        if subset not in KEEP:
            continue
        url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
        family = re.search(r"font-family: '([^']+)'", block).group(1).replace(" ", "")
        weight = re.search(r"font-weight: (\d+)", block).group(1)
        if url not in saved:                     # a variable font is one file for every weight
            saved[url] = "%s-%s.woff2" % (family, subset)
            (out_dir / saved[url]).write_bytes(get(url))
        name = saved[url]
        css_parts.append(block.replace(url, "/fonts/" + name))
    (ROOT / "app" / "fonts-local.css").write_text("\n".join(css_parts) + "\n")
    print("wrote %d @font-face rules" % (len(css_parts) - 1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
