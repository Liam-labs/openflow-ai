#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md from the packages a production install actually contains.

    python3 scripts/generate-third-party-notices.py [--check]

Reads package-lock.json for every package that is not development-only, then each installed package's own package.json for its
licence, version and repository. Needs `npm ci` to have run. With --check it writes nothing and exits 1 when the file on disk
differs from what would be written, so CI can keep the notices true. Packages with no declared licence, or a licence outside the
accepted list, are reported and make the run fail: a human decides before they ship.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"

# Licences that need nothing more than being listed (permissive).
ACCEPTED = {
    "MIT", "ISC", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "0BSD", "BlueOak-1.0.0", "CC0-1.0", "Unlicense",
    "Python-2.0", "MIT-0", "OFL-1.1", "SIL OPEN FONT LICENSE", "MPL-2.0", "CC-BY-4.0", "LGPL-3.0-or-later", "LGPL-3.0",
}
# Notes shown beside licences with a condition.
CONDITIONS = {
    "MPL-2.0": "file-level copyleft: changes to the package's own files must be shared; using it as a dependency is fine",
    "CC-BY-4.0": "attribution required (listed here)",
    "LGPL-3.0-or-later": "installed as a separate library by npm and not copied into this repository; keep it replaceable",
    "LGPL-3.0": "installed as a separate library by npm and not copied into this repository; keep it replaceable",
    "OFL-1.1": "font licence: keep the licence with the font files",
    "SIL OPEN FONT LICENSE": "font licence: keep the licence with the font files",
}


# Packages whose licence sits in a LICENSE file but not in package.json (checked by reading the files, 21 Oct 2026).
OVERRIDES = {"khroma": "MIT", "sylvester": "MIT"}


def licence_of(meta):
    value = meta.get("license") or meta.get("licenses")
    if isinstance(value, dict):
        value = value.get("type")
    if isinstance(value, list):
        value = " OR ".join(str(v.get("type") if isinstance(v, dict) else v) for v in value)
    return str(value).strip() if value else ""


def accepted(licence):
    parts = [p.strip(" ()") for p in licence.replace(" AND ", " OR ").split(" OR ")]
    return bool(parts) and any(p in ACCEPTED for p in parts)


def collect():
    lock = json.loads((ROOT / "package-lock.json").read_text())
    rows, problems = {}, []
    for path, entry in lock.get("packages", {}).items():
        if not path or entry.get("dev"):
            continue
        name = path.split("node_modules/")[-1]
        pkg_file = ROOT / path / "package.json"
        meta = json.loads(pkg_file.read_text()) if pkg_file.exists() else {}
        licence = licence_of(meta) or str(entry.get("license") or "").strip() or OVERRIDES.get(name, "")
        version = meta.get("version") or entry.get("version") or "?"
        repo = meta.get("repository")
        repo = repo.get("url") if isinstance(repo, dict) else repo
        if not licence:
            problems.append("%s@%s declares no licence" % (name, version))
        elif not accepted(licence):
            problems.append("%s@%s has licence %s, which is not on the accepted list" % (name, version, licence))
        rows[(name, version)] = (licence or "UNKNOWN", repo or meta.get("homepage") or "")
    return rows, problems


def render(rows):
    lines = ["# Third-party notices", "",
             "This product depends on the open-source packages below. Each is used under its own licence; the licence text ships",
             "inside the installed package. This file is generated by `scripts/generate-third-party-notices.py`: do not edit it by hand.", ""]
    conditional = sorted({lic for lic, _ in rows.values() if lic in CONDITIONS})
    if conditional:
        lines += ["## Licences with a condition", ""]
        for lic in conditional:
            lines.append("- **%s**: %s." % (lic, CONDITIONS[lic]))
        lines.append("")
    lines += ["## Packages", "", "| Package | Version | Licence | Source |", "|---|---|---|---|"]
    for (name, version), (lic, repo) in sorted(rows.items()):
        lines.append("| %s | %s | %s | %s |" % (name, version, lic, repo.replace("git+", "").replace("|", "/")))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rows, problems = collect()
    text = render(rows)
    for problem in problems:
        print("PROBLEM:", problem, file=sys.stderr)
    if args.check:
        same = OUT.exists() and OUT.read_text() == text
        print("up to date" if same else "THIRD_PARTY_NOTICES.md is out of date")
        return 0 if same and not problems else 1
    OUT.write_text(text)
    print("wrote %s: %d packages, %d problems" % (OUT.name, len(rows), len(problems)))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
