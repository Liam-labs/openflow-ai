#!/usr/bin/env python3
"""Where an agent runs: the permanent note and the per-session note.

Agents can run on the desktop PC or on the DevFlow server (the laptop), and the
same agent can move between them. So the two things an agent needs are kept
apart:

* the **permanent note** (`Runtime-Location.md`, loaded every session) holds
  only what does not depend on where the agent is: both machines and how each
  service is reached from each of them. It is identical for every agent.
* the **session note** is printed at the start of each session, and again after
  a compaction, and says which machine this session is on. It is marked
  do-not-save, so an agent that later moves has no stale location in memory.

Both are generated from `service-locations.json`, the single source of truth.
`sync.py` imports this module for the permanent note; the session-start hooks
and the Codex wrapper call `python3 runtime_location.py session-note`.
"""
from __future__ import annotations

import argparse
import json
import os
import socket
import sys
from pathlib import Path

REGISTRY = Path(__file__).resolve().parent / "service-locations.json"
LOCATIONS = ("desktop-wsl", "desktop-windows", "server")
ENV_VAR = "DEVFLOW_RUN_LOCATION"

def devflow_setting(name):
    """A non-secret DevFlow setting: the environment first, then ~/.config/devflow/env (KEY=VALUE lines)."""
    value = os.environ.get(name, "").strip()
    if value:
        return value
    try:
        for line in (Path.home() / ".config" / "devflow" / "env").read_text().splitlines():
            key, sep, val = line.strip().removeprefix("export ").partition("=")
            if sep and key.strip() == name:
                return val.strip().strip("'\"")
    except OSError:
        pass
    return ""


OWNER = devflow_setting("DEVFLOW_OWNER_NAME") or "the owner"
HOME_USER = Path.home().name



def active_services(registry: dict) -> list[dict]:
    """The registry's services as they stand in its active layout.

    The registry holds today's layout plus, per service, an optional
    `atCutover` or `atFailover` block (runsOn/reach/notes). `"layout"` picks
    which block replaces the service's own fields.
    """
    layout = registry.get("layout")
    key = {"cutover": "atCutover", "failover": "atFailover"}.get(layout)
    return [{**svc, **(svc.get(key) or {})} if key else svc
            for svc in registry.get("services", [])]


def host_of(location: str) -> str:
    return "server" if location == "server" else "desktop"


def detect_location(registry: dict, environ: dict | None = None, hostname: str | None = None) -> str | None:
    """This session's location, or None when it cannot be told.

    The spawning code states it with DEVFLOW_RUN_LOCATION; otherwise the
    machine's hostname is matched against the registry's host `hostnames`.
    A Windows-launched agent is only identified by the explicit variable.
    """
    env = os.environ if environ is None else environ
    stated = (env.get(ENV_VAR) or "").strip().lower()
    if stated in LOCATIONS:
        return stated
    name = (hostname if hostname is not None else socket.gethostname()).strip().lower()
    for host_id, host in registry.get("hosts", {}).items():
        names = {n.lower() for n in host.get("hostnames", [])}
        if name in names:
            return "server" if host_id == "server" else "desktop-wsl"
    return None


def _render_single_machine_note(registry: dict) -> str:
    """An installation with one machine (no separate server): DevFlow and its agents all run on it."""
    host = (registry.get("hosts") or {}).get("desktop", {})
    lines = [
        "# Where you run",
        "",
        "Generated by `sync.py` from `data/scaffolding/service-locations.json`.",
        "Do not edit this file; update the registry instead.",
        "",
        f"DevFlow and its agents run on one machine: {host.get('label') or host.get('name') or 'this computer'}. "
        f"{host.get('note') or host.get('description') or ''}".rstrip(),
        "",
        "Use the address in the table for each service, and the named environment variable when one is given.",
        "",
        "| Service | Address | Env var |",
        "|---|---|---|",
    ]
    for svc in active_services(registry):
        reach = svc.get("reach") or {}
        env = f"`{svc['env']}`" if svc.get("env") else ""
        lines.append(f"| {svc.get('name', '?')} | {reach.get('desktop', 'not listed')} | {env} |")
    lines += [
        "",
        "## When something you need isn't listed",
        "Check the registry file for newer entries before assuming an address. If you",
        "build or retire a service, update `service-locations.json` first and",
        "run `sync.py --runtime-location-only` so every agent learns the change.",
        "",
    ]
    return "\n".join(lines)


def render_permanent_note(registry: dict) -> str:
    """Location-neutral: the same text for every agent, wherever it runs."""
    hosts = registry.get("hosts", {})
    if "server" not in hosts:
        return _render_single_machine_note(registry)
    desk, srv = hosts.get("desktop", {}), hosts.get("server", {})
    lines = [
        "# Where you run",
        "",
        "Generated by `sync.py` from `~/DevFlow/data/scaffolding/service-locations.json`.",
        "Do not edit this file; update the registry instead.",
        "",
        "Agents here run on one of two machines, and the same agent can move from one to",
        "the other between sessions:",
        "",
        f"- **Desktop:** {desk.get('name', 'desktop')} (Tailscale `{desk.get('tailscaleName', '?')}`; "
        f"{desk.get('os', '')}). {desk.get('description', '')}",
        f"- **Laptop (DevFlow server):** {srv.get('name', 'server')} (Tailscale "
        f"`{srv.get('tailscaleName', '?')}`; {srv.get('os', '')}). {srv.get('description', '')}",
        "",
        "**Which one you are on now is not recorded here.** Each session starts with a note",
        "headed \"Session location (do not save)\"; it is the only place your current machine",
        "is stated. Without it, run `hostname` and match it to the machines above.",
        "",
        "**Never save where you run.** Do not write your machine, a `localhost` address or any",
        "reach instruction below into `MEMORY.md`, `Expertise.md`, the handoff, task notes or",
        "the knowledge base as a fact about you. It is true for one session only, and you may",
        "be restarted on the other machine.",
        "",
        "Only what a row below says runs on your machine is local to you. Never assume a",
        "service is on `localhost` because it used to be: use the column for your machine and",
        "prefer the named environment variable when one is given.",
        "",
        "| Service | Runs on | From the desktop | From the laptop | Env var |",
        "|---|---|---|---|---|",
    ]
    for svc in active_services(registry):
        reach = svc.get("reach") or {}
        runs_on = hosts.get(svc.get("runsOn", ""), {}).get("tailscaleName", svc.get("runsOn", "?"))
        env = f"`{svc['env']}`" if svc.get("env") else ""
        lines.append(f"| {svc.get('name', '?')} | `{runs_on}` | "
                     f"{reach.get('desktop', 'not listed')} | {reach.get('server', 'not listed')} | {env} |")
    lines += [
        "",
        "## When something you need isn't listed",
        "Check the registry file for newer entries before assuming an address. If you",
        "build, move or retire a service, update `service-locations.json` first and",
        "run `sync.py --runtime-location-only` so every agent learns the change.",
        "",
    ]
    return "\n".join(lines)


def render_session_note(registry: dict, location: str | None) -> str:
    """The short, do-not-save note for one session.

    The Run locally / Run remote choice in the agent's configuration decides the
    location (the spawn code sets DEVFLOW_RUN_LOCATION), and so decides what this
    note tells the agent about where its tool calls and commands run.
    """
    head = ["## Session location (do not save)", ""]
    if location is None:
        return "\n".join(head + [
            "This session's machine could not be identified. Run `hostname` and match it to the",
            "machines in your `Runtime-Location.md`. Do not save the result to memory.",
            "",
        ])
    hosts = registry.get("hosts", {})
    here = host_of(location)
    other = "desktop" if here == "server" else "server"
    me, them = hosts.get(here, {}), hosts.get(other, {})
    remote = location == "server"
    column = "From the laptop" if remote else "From the desktop"
    kind = {"server": "running REMOTELY, on the laptop (the DevFlow server)",
            "desktop-wsl": f"running LOCALLY, on {OWNER}'s desktop (WSL)",
            "desktop-windows": f"running LOCALLY, on {OWNER}'s desktop (Windows PowerShell)"}[location]
    lines = head + [
        "This is where you run in **this session only**. It changes if you are restarted on",
        "the other machine, so do not write it, or any address that depends on it, into",
        "memory, Expertise, the handoff or notes. It replaces any earlier session-location",
        "note in this conversation.",
        "",
        f"You are {kind}: **{me.get('name', here)}** "
        f"(Tailscale `{me.get('tailscaleName', '?')}`). The other machine is "
        f"**{them.get('name', other)}**. In the service table in `Runtime-Location.md`, use the "
        f"**{column}** column.",
        "",
    ]
    if location == "desktop-windows":
        lines += ["- Your tool calls and commands run on the desktop, as Windows `claude.exe`. WSL paths such as",
                  f"  `/home/{HOME_USER}/...` are reached as `Z:\\home\\{HOME_USER}\\...`. Your hooks run inside WSL."]
    elif location == "desktop-wsl":
        lines += ["- Your tool calls and commands run on the desktop. Your working folder and DevFlow's scripts,",
                  "  skills and roles are local files, so git, builds and tests run here as usual."]
    else:
        caps = registry.get("remote", {})
        lines += [f"- Your tool calls and shell commands run **on the laptop**, not on {OWNER}'s desktop."]
        if caps.get("fileShare"):
            lines += ["- Desktop files: " + caps.get("fileShareNote", "shared at the same paths.")]
        else:
            lines += ["- Desktop project files are not mounted here: do not assume desktop paths exist."]
        if caps.get("desktopCommands"):
            lines += ["- Desktop commands: " + caps.get("desktopCommandsNote", "available.")]
        else:
            lines += ["- You cannot run commands on the desktop. If a task needs one (git or a build in a desktop",
                      "  project, a Windows program), say so in the channel for a desktop agent; do not try ssh."]
        for note in caps.get("toolNotes", []):
            lines.append(f"- Tools: {note}")
        if caps.get("fileShare"):
            lines += ["- If the desktop is off or asleep you cannot reach its files: say so, do not retry."]
    lines.append("")
    return "\n".join(lines)


def load_registry(path: Path = REGISTRY) -> dict:
    return json.loads(path.read_text())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("what", choices=["session-note", "permanent-note", "location"])
    parser.add_argument("--registry", type=Path, default=REGISTRY)
    parser.add_argument("--location", choices=LOCATIONS, help="Override detection (testing)")
    args = parser.parse_args(argv)
    try:
        registry = load_registry(args.registry)
    except (OSError, json.JSONDecodeError) as error:
        print(f"runtime_location: registry unreadable: {error}", file=sys.stderr)
        return 1
    location = args.location or detect_location(registry)
    if args.what == "permanent-note":
        sys.stdout.write(render_permanent_note(registry))
    elif args.what == "location":
        print(location or "unknown")
    else:
        sys.stdout.write(render_session_note(registry, location))
    return 0


if __name__ == "__main__":
    sys.exit(main())
