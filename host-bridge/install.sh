#!/usr/bin/env bash
# Host-Bridge Install Script
# Sets up the host-bridge daemon as a system service.
# Primary: systemd unit. Fallback: PM2.
# Works on: Ubuntu/Debian, WSL2, macOS.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
DEVFLOW_HOME="${DEVFLOW_HOME:-$(dirname "$SCRIPT_DIR")}"
BRIDGE_DIR="${DEVFLOW_HOME}/host-bridge"
CONFIG_DIR="${DEVFLOW_HOME}/config"
CONFIG_FILE="${CONFIG_DIR}/host-bridge.json"
LOG_DIR="${DEVFLOW_HOME}/logs/host-bridge"
SERVICE_NAME="openflow-host-bridge"
DEFAULT_PORT=3001

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[0;33m'
NC='\033[0m'

info()  { echo -e "${GREEN}[install]${NC} $1"; }
warn()  { echo -e "${YELLOW}[install]${NC} $1"; }
error() { echo -e "${RED}[install]${NC} $1"; }

# ============================================
# Checks
# ============================================

check_node() {
  if ! command -v node &>/dev/null; then
    error "Node.js not found. Install Node.js 18+ first."
    exit 1
  fi

  local version
  version=$(node -v | sed 's/v//' | cut -d. -f1)
  if [ "$version" -lt 18 ]; then
    error "Node.js 18+ required. Found: $(node -v)"
    exit 1
  fi

  info "Node.js $(node -v) found"
}

check_npm() {
  if ! command -v npm &>/dev/null; then
    error "npm not found."
    exit 1
  fi
  info "npm $(npm -v) found"
}

detect_platform() {
  if [ -f /proc/version ] && grep -qi microsoft /proc/version 2>/dev/null; then
    echo "wsl"
  elif [ "$(uname)" = "Darwin" ]; then
    echo "macos"
  elif [ -d /run/systemd/system ]; then
    echo "systemd"
  else
    echo "generic"
  fi
}

find_free_port() {
  local port=$DEFAULT_PORT
  while ss -tlnp 2>/dev/null | grep -q ":${port} " || \
        netstat -tlnp 2>/dev/null | grep -q ":${port} "; do
    port=$((port + 1))
    if [ "$port" -gt 3100 ]; then
      warn "No free port found in range 3001-3100. Using $DEFAULT_PORT anyway."
      port=$DEFAULT_PORT
      break
    fi
  done
  echo "$port"
}

# ============================================
# Install Steps
# ============================================

install_deps() {
  info "Installing dependencies..."
  cd "$BRIDGE_DIR"
  npm install --production 2>&1 | tail -3
  info "Dependencies installed"
}

generate_token() {
  # Generate a random 32-byte hex token
  if command -v openssl &>/dev/null; then
    openssl rand -hex 32
  else
    node -e "console.log(require('crypto').randomBytes(32).toString('hex'))"
  fi
}

create_config() {
  if [ -f "$CONFIG_FILE" ]; then
    info "Config already exists at ${CONFIG_FILE}"
    return
  fi

  local port
  port=$(find_free_port)
  local token
  token=$(generate_token)

  mkdir -p "$CONFIG_DIR"

  cat > "$CONFIG_FILE" << CONFIGEOF
{
  "port": ${port},
  "host": "127.0.0.1",
  "authToken": "${token}",
  "pm2Allowlist": [
    "^pm2 jlist$",
    "^pm2 (start|stop|restart) [\\\\w-]+$",
    "^pm2 logs [\\\\w-]+ --nostream --lines \\\\d+$",
    "^pm2 describe [\\\\w-]+$"
  ],
  "scriptAllowlist": [
    { "name": "safe-build.sh", "description": "Atomic Next.js build", "maxTimeout": 600000 },
    { "name": "ensure-build.sh", "description": "Verify build exists" },
    { "name": "devflow-debug.sh", "description": "Diagnostics report" },
    { "name": "rollout-agent-dirs.py", "description": "Scaffold agent directories" },
    { "name": "check-rotate.sh", "description": "Rotate agent log files" },
    { "name": "write-session-end.sh", "description": "Write session end marker" },
    { "name": "patch-hooks.py", "description": "Update agent hooks" },
    { "name": "rotate-logs.sh", "description": "Rotate system logs" },
    { "name": "collab_helper.py", "description": "Send collab channel message" }
  ],
  "rateLimit": { "pm2": 60, "pty": 30, "script": 10 },
  "maxPtySessions": 20,
  "auditRetentionDays": 7
}
CONFIGEOF

  info "Config created at ${CONFIG_FILE}"
  info "Auth token generated (save this for OpenFlow config):"
  echo ""
  echo "  HOST_BRIDGE_TOKEN=${token}"
  echo ""

  # Also add to ~/.secrets if it exists
  if [ -f "$HOME/.secrets" ]; then
    if ! grep -q 'HOST_BRIDGE_TOKEN' "$HOME/.secrets"; then
      echo "" >> "$HOME/.secrets"
      echo "# Host-bridge auth token (generated by install.sh)" >> "$HOME/.secrets"
      echo "export HOST_BRIDGE_TOKEN=\"${token}\"" >> "$HOME/.secrets"
      info "Token added to ~/.secrets"
    else
      warn "HOST_BRIDGE_TOKEN already exists in ~/.secrets — not overwriting"
    fi
  fi

  info "Bridge will listen on port ${port}"
}

create_log_dir() {
  mkdir -p "$LOG_DIR"
  info "Log directory: ${LOG_DIR}"
}

# ============================================
# Service Setup
# ============================================

setup_systemd() {
  local node_path
  node_path=$(which node)
  local npx_path
  npx_path=$(which npx)
  local user
  user=$(whoami)

  local unit_file="/etc/systemd/system/${SERVICE_NAME}.service"

  info "Creating systemd unit: ${unit_file}"

  sudo tee "$unit_file" > /dev/null << UNITEOF
[Unit]
Description=OpenFlow Host-Bridge Daemon
After=network.target

[Service]
Type=simple
User=${user}
WorkingDirectory=${BRIDGE_DIR}
ExecStart=${npx_path} tsx src/server.ts
Restart=on-failure
RestartSec=5
Environment=NODE_ENV=production
Environment=DEVFLOW_HOME=${DEVFLOW_HOME}
EnvironmentFile=-${HOME}/.secrets

# Security hardening
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=read-only
ReadWritePaths=${DEVFLOW_HOME}/logs ${DEVFLOW_HOME}/config /tmp/DevFlow
PrivateTmp=false

[Install]
WantedBy=multi-user.target
UNITEOF

  sudo systemctl daemon-reload
  sudo systemctl enable "$SERVICE_NAME"
  sudo systemctl start "$SERVICE_NAME"

  info "systemd service installed and started"
}

setup_pm2() {
  if ! command -v pm2 &>/dev/null; then
    warn "PM2 not found. Install with: npm install -g pm2"
    warn "Then run: pm2 start ${BRIDGE_DIR}/src/server.ts --name ${SERVICE_NAME} --interpreter npx -- tsx"
    return 1
  fi

  # Source secrets for the token
  if [ -f "$HOME/.secrets" ]; then
    # shellcheck disable=SC1091
    source "$HOME/.secrets"
  fi

  pm2 start "npx" \
    --name "$SERVICE_NAME" \
    --cwd "$BRIDGE_DIR" \
    -- tsx src/server.ts

  pm2 save

  info "PM2 process started: ${SERVICE_NAME}"
}

# ============================================
# Verification
# ============================================

verify_health() {
  local port
  port=$(node -e "
    try {
      const c = require('${CONFIG_FILE}');
      console.log(c.port || ${DEFAULT_PORT});
    } catch { console.log(${DEFAULT_PORT}); }
  " 2>/dev/null)

  info "Waiting for bridge to start on port ${port}..."

  local attempts=0
  while [ $attempts -lt 10 ]; do
    if curl -sf "http://127.0.0.1:${port}/health" > /dev/null 2>&1; then
      local response
      response=$(curl -sf "http://127.0.0.1:${port}/health")
      info "Health check passed: ${response}"
      return 0
    fi
    sleep 1
    attempts=$((attempts + 1))
  done

  warn "Health check failed after 10 attempts. Check logs:"
  warn "  systemd: journalctl -u ${SERVICE_NAME} -n 20"
  warn "  PM2: pm2 logs ${SERVICE_NAME} --lines 20"
  return 1
}

# ============================================
# Main
# ============================================

main() {
  echo ""
  echo "OpenFlow Host-Bridge Installer"
  echo "============================="
  echo ""

  local platform
  platform=$(detect_platform)
  info "Platform: ${platform}"
  info "DEVFLOW_HOME: ${DEVFLOW_HOME}"
  info "Bridge dir: ${BRIDGE_DIR}"

  # Skip checks in --skip mode
  if [ "${1:-}" = "--skip" ]; then
    info "Skip mode — verifying health only"
    verify_health
    exit $?
  fi

  check_node
  check_npm
  install_deps
  create_config
  create_log_dir

  echo ""
  info "Setting up service..."

  case "$platform" in
    systemd)
      setup_systemd
      ;;
    wsl)
      info "WSL detected — systemd may not be available. Using PM2."
      setup_pm2
      ;;
    macos)
      info "macOS detected — using PM2 (launchd support coming later)."
      setup_pm2
      ;;
    *)
      if [ -d /run/systemd/system ] 2>/dev/null; then
        setup_systemd
      else
        info "No systemd — falling back to PM2."
        setup_pm2
      fi
      ;;
  esac

  echo ""
  verify_health

  echo ""
  info "Installation complete!"
  echo ""
  echo "  Service: ${SERVICE_NAME}"
  echo "  Config:  ${CONFIG_FILE}"
  echo "  Logs:    ${LOG_DIR}/"
  echo ""
}

main "$@"
